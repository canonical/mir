//! Emits the C++ header and source of a protocol's typed wrapper.

use crate::model::{version_supports, Arg, Interface, Kind, Message, Protocol};
use std::collections::BTreeSet;
use std::fmt::Write;

macro_rules! out {
    ($dst:expr) => { $dst.push('\n') };
    ($dst:expr, $($arg:tt)*) => { writeln!($dst, $($arg)*).unwrap() };
}

pub fn header(protocol: &Protocol, xml_file: &str) -> String {
    let mut o = String::new();
    let guard = format!(
        "MIR_WAYLAND_GENERATED_{}_WRAPPER_H_",
        protocol.namespace.to_uppercase()
    );

    out!(
        o,
        "// Generated by mir_wayland_generator from {xml_file}. Do not edit."
    );
    out!(o);
    out!(o, "#ifndef {guard}");
    out!(o, "#define {guard}");
    out!(o);
    out!(o, "#include \"wayland_rs/src/ffi.rs.h\"");
    out!(o);
    out!(o, "#include <mir/fd.h>");
    out!(o);
    out!(o, "#include <cstdint>");
    out!(o, "#include <memory>");
    out!(o, "#include <optional>");
    out!(o, "#include <string>");
    out!(o, "#include <vector>");
    out!(o);
    out!(o, "namespace mir");
    out!(o, "{{");
    out!(o, "namespace wayland");
    out!(o, "{{");
    out!(o, "namespace {}", protocol.namespace);
    out!(o, "{{");
    out!(
        o,
        "/// Registers the `{}` protocol with the Wayland server, so that its",
        protocol.name
    );
    out!(
        o,
        "/// globals can be created. Calling it again has no effect."
    );
    out!(o, "///");
    out!(
        o,
        "/// The `Global::create` functions call this, so it rarely needs calling directly."
    );
    out!(o, "void register_protocol();");
    out!(o);
    for interface in &protocol.interfaces {
        out!(o, "class {};", interface.class);
    }
    for interface in &protocol.interfaces {
        out!(o);
        class_declaration(&mut o, protocol, interface);
    }
    out!(o, "}}");
    out!(o, "}}");
    out!(o, "}}");
    out!(o);
    out!(o, "#endif // {guard}");
    o
}

fn class_declaration(o: &mut String, protocol: &Protocol, interface: &Interface) {
    let class = &interface.class;

    out!(o, "/// The server side of `{}` objects.", interface.name);
    out!(o, "///");
    out!(
        o,
        "/// Derive from this to implement the requests. All calls happen on the Wayland"
    );
    out!(
        o,
        "/// event-loop thread. Throwing `mir::wayland::ProtocolError` from a request"
    );
    out!(o, "/// posts that error to the client.");
    out!(o, "class {class} : public DynamicResourceHandler");
    out!(o, "{{");
    out!(o, "public:");
    out!(
        o,
        "    static constexpr char const* interface_name = \"{}\";",
        interface.name
    );
    out!(
        o,
        "    static constexpr uint32_t interface_version = {};",
        interface.version
    );

    for enumeration in &interface.enums {
        out!(o);
        out!(o, "    struct {}", enumeration.type_name);
        out!(o, "    {{");
        for (name, value) in &enumeration.entries {
            out!(
                o,
                "        static constexpr uint32_t {name} = {}u;",
                *value as u32
            );
        }
        out!(o, "    }};");
    }

    if interface.is_global {
        out!(o);
        out!(o, "    /// Advertises `{}` to clients.", interface.name);
        out!(o, "    class Global : public DynamicGlobalHandler");
        out!(o, "    {{");
        out!(o, "    public:");
        out!(o, "        /// Registers the protocol, then creates the global on `server`, which must be");
        out!(o, "        /// running. Call on the Wayland event-loop thread. The global is removed when");
        out!(o, "        /// the result is dropped.");
        out!(o, "        static auto create(");
        out!(o, "            WaylandServer const& server,");
        out!(o, "            std::unique_ptr<Global> global,");
        out!(
            o,
            "            uint32_t version = interface_version) -> rust::Box<DynamicGlobal>;"
        );
        out!(o);
        out!(o, "        auto bind(rust::Box<WaylandClient> client, rust::Box<DynamicResource> resource)");
        out!(
            o,
            "            -> std::shared_ptr<DynamicResourceHandler> final;"
        );
        out!(o);
        out!(o, "    protected:");
        out!(
            o,
            "        /// `client` has bound the global, creating `resource`. Return its handler."
        );
        out!(o, "        virtual auto on_bind(rust::Box<WaylandClient> client, rust::Box<DynamicResource> resource)");
        out!(o, "            -> std::shared_ptr<{class}> = 0;");
        out!(o, "    }};");
    }

    out!(o);
    out!(
        o,
        "    /// Takes ownership of `resource`, which must be a `{}`.",
        interface.name
    );
    out!(
        o,
        "    explicit {class}(rust::Box<DynamicResource> resource);"
    );
    out!(o);
    out!(o, "    auto resource() const -> DynamicResource const&;");
    out!(o, "    auto object_id() const -> uint32_t;");
    out!(o, "    auto version() const -> uint32_t;");
    out!(o, "    auto is_alive() const -> bool;");
    out!(o, "    auto client() const -> rust::Box<WaylandClient>;");
    out!(
        o,
        "    void post_error(uint32_t code, std::string const& message) const;"
    );
    out!(o, "    /// Destroys the object from the server side.");
    out!(o, "    void destroy_resource() const;");

    if !interface.events.is_empty() {
        out!(o);
    }
    for event in &interface.events {
        if event.since > 1 {
            out!(o, "    auto {}() const -> bool;", version_supports(event));
        }
        if let Some(new_id) = event.new_id() {
            out!(
                o,
                "    /// Sets `{}` as the handler of its resource.",
                new_id.param
            );
        }
        out!(
            o,
            "    void {}({}) const;",
            event.method,
            event_params(protocol, event)
        );
    }

    out!(o);
    out!(
        o,
        "    void on_request(uint32_t opcode, rust::Vec<DynamicArgument> args) final;"
    );
    if interface
        .requests
        .iter()
        .any(|request| request.new_id().is_some())
    {
        out!(o, "    auto on_constructor_request(");
        out!(o, "        uint32_t opcode,");
        out!(o, "        rust::Vec<DynamicArgument> args,");
        out!(o, "        rust::Box<DynamicResource> new_resource) -> std::shared_ptr<DynamicResourceHandler> final;");
    }

    if !interface.requests.is_empty() {
        out!(o);
        out!(o, "protected:");
    }
    for request in &interface.requests {
        let params = request_params(protocol, request);
        match request.new_id() {
            Some(new_id) => {
                out!(o, "    /// Return the handler of `{}`.", new_id.param);
                out!(
                    o,
                    "    virtual auto {}({params}) -> {} = 0;",
                    request.method,
                    handler_type(protocol, new_id)
                );
            }
            None if request.is_destructor => {
                let unnamed = request_params_unnamed(protocol, request);
                out!(o, "    virtual void {}({unnamed}) {{}}", request.method);
            }
            None => out!(o, "    virtual void {}({params}) = 0;", request.method),
        }
    }

    out!(o);
    out!(o, "private:");
    out!(o, "    rust::Box<DynamicResource> const resource_;");
    out!(o, "}};");
}

/// The handler type for an object of `arg`'s interface.
fn handler_type(protocol: &Protocol, arg: &Arg) -> String {
    match arg
        .interface
        .as_deref()
        .and_then(|name| protocol.class_of(name))
    {
        Some(class) => format!("std::shared_ptr<{class}>"),
        None => "std::shared_ptr<DynamicResourceHandler>".into(),
    }
}

fn request_param_type(protocol: &Protocol, arg: &Arg) -> String {
    match arg.kind {
        Kind::Int => "int32_t".into(),
        Kind::Uint => "uint32_t".into(),
        Kind::Fixed => "double".into(),
        Kind::String if arg.allow_null => "std::optional<std::string> const&".into(),
        Kind::String => "std::string const&".into(),
        Kind::Object => match arg
            .interface
            .as_deref()
            .and_then(|name| protocol.class_of(name))
        {
            Some(class) => format!("std::shared_ptr<{class}> const&"),
            None => "uint32_t".into(),
        },
        Kind::NewId => "rust::Box<DynamicResource>".into(),
        Kind::Array => "std::vector<uint8_t> const&".into(),
        Kind::Fd => "mir::Fd".into(),
    }
}

fn event_param_type(protocol: &Protocol, arg: &Arg) -> String {
    match arg.kind {
        Kind::NewId => handler_type(protocol, arg) + " const&",
        Kind::Fd => "int32_t".into(),
        _ => request_param_type(protocol, arg),
    }
}

fn request_params(protocol: &Protocol, request: &Message) -> String {
    join(
        request
            .args
            .iter()
            .map(|arg| format!("{} {}", request_param_type(protocol, arg), arg.param)),
    )
}

fn request_params_unnamed(protocol: &Protocol, request: &Message) -> String {
    join(
        request
            .args
            .iter()
            .map(|arg| format!("{} /*{}*/", request_param_type(protocol, arg), arg.param)),
    )
}

fn event_params(protocol: &Protocol, event: &Message) -> String {
    join(
        event
            .args
            .iter()
            .map(|arg| format!("{} {}", event_param_type(protocol, arg), arg.param)),
    )
}

fn join(items: impl Iterator<Item = String>) -> String {
    items.collect::<Vec<_>>().join(", ")
}

/// Functions in the source's anonymous namespace, emitted only when used (unused ones
/// would fail `-Werror=unused-function`).
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Helper {
    ArgumentDescriptor,
    MessageDescriptor,
    ToString,
    ToOptionalString,
    ToVector,
    FromFixed,
    ToHandler,
    IntArgument,
    UintArgument,
    FixedArgument,
    StringArgument,
    OptionalStringArgument,
    ArrayArgument,
    FdArgument,
    ObjectArgument,
    HandlerArgument,
    NewIdArgument,
}

impl Helper {
    fn definition(self) -> &'static str {
        match self {
            Helper::ArgumentDescriptor => {
                "auto argument(char const* name, mw::DynamicArgumentKind kind, bool allow_null, char const* interface)
    -> mw::DynamicArgumentDescriptor
{
    mw::DynamicArgumentDescriptor result;
    result.name = rust::String{name};
    result.kind = kind;
    result.allow_null = allow_null;
    result.interface = rust::String{interface};
    return result;
}"
            }
            Helper::MessageDescriptor => {
                "auto message(
    char const* name,
    uint32_t since,
    bool is_destructor,
    std::initializer_list<mw::DynamicArgumentDescriptor> args) -> mw::DynamicMessageDescriptor
{
    mw::DynamicMessageDescriptor result;
    result.name = rust::String{name};
    result.since = since;
    result.is_destructor = is_destructor;
    for (auto const& arg : args)
        result.args.push_back(arg);
    return result;
}"
            }
            Helper::ToString => {
                "auto to_string(mw::DynamicArgument const& arg) -> std::string
{
    return std::string{arg.string_value};
}"
            }
            Helper::ToOptionalString => {
                "auto to_optional_string(mw::DynamicArgument const& arg) -> std::optional<std::string>
{
    if (arg.is_null)
        return std::nullopt;
    return std::string{arg.string_value};
}"
            }
            Helper::ToVector => {
                "auto to_vector(mw::DynamicArgument const& arg) -> std::vector<uint8_t>
{
    return std::vector<uint8_t>(arg.array_value.begin(), arg.array_value.end());
}"
            }
            Helper::FromFixed => {
                "auto from_fixed(int32_t raw) -> double
{
    return raw / 256.0;
}"
            }
            Helper::ToHandler => {
                "template<typename Handler>
auto to_handler(mw::DynamicArgument const& arg) -> std::shared_ptr<Handler>
{
    if (arg.object_id == 0)
        return nullptr;
    if (auto handler = std::dynamic_pointer_cast<Handler>(arg.object_handler))
        return handler;
    throw std::logic_error{
        \"Object \" + std::to_string(arg.object_id) + \" has no \" + Handler::interface_name + \" handler\"};
}"
            }
            Helper::IntArgument => {
                "auto int_argument(int32_t value) -> mw::DynamicArgument
{
    mw::DynamicArgument arg{};
    arg.kind = mw::DynamicArgumentKind::Int;
    arg.int_value = value;
    return arg;
}"
            }
            Helper::UintArgument => {
                "auto uint_argument(uint32_t value) -> mw::DynamicArgument
{
    mw::DynamicArgument arg{};
    arg.kind = mw::DynamicArgumentKind::Uint;
    arg.uint_value = value;
    return arg;
}"
            }
            Helper::FixedArgument => {
                "auto fixed_argument(double value) -> mw::DynamicArgument
{
    mw::DynamicArgument arg{};
    arg.kind = mw::DynamicArgumentKind::Fixed;
    arg.int_value = static_cast<int32_t>(std::lround(value * 256.0));
    return arg;
}"
            }
            Helper::StringArgument => {
                "auto string_argument(std::string const& value) -> mw::DynamicArgument
{
    mw::DynamicArgument arg{};
    arg.kind = mw::DynamicArgumentKind::String;
    arg.string_value = rust::String{value};
    return arg;
}"
            }
            Helper::OptionalStringArgument => {
                "auto optional_string_argument(std::optional<std::string> const& value) -> mw::DynamicArgument
{
    mw::DynamicArgument arg{};
    arg.kind = mw::DynamicArgumentKind::String;
    arg.is_null = !value;
    if (value)
        arg.string_value = rust::String{*value};
    return arg;
}"
            }
            Helper::ArrayArgument => {
                "auto array_argument(std::vector<uint8_t> const& value) -> mw::DynamicArgument
{
    mw::DynamicArgument arg{};
    arg.kind = mw::DynamicArgumentKind::Array;
    arg.array_value.reserve(value.size());
    for (auto const byte : value)
        arg.array_value.push_back(byte);
    return arg;
}"
            }
            Helper::FdArgument => {
                "auto fd_argument(int32_t fd) -> mw::DynamicArgument
{
    mw::DynamicArgument arg{};
    arg.kind = mw::DynamicArgumentKind::Fd;
    arg.fd = fd;
    return arg;
}"
            }
            Helper::ObjectArgument => {
                "auto object_argument(uint32_t object_id) -> mw::DynamicArgument
{
    mw::DynamicArgument arg{};
    arg.kind = mw::DynamicArgumentKind::Object;
    arg.object_id = object_id;
    return arg;
}"
            }
            Helper::HandlerArgument => {
                "template<typename Handler>
auto handler_argument(std::shared_ptr<Handler> const& handler) -> mw::DynamicArgument
{
    mw::DynamicArgument arg{};
    arg.kind = mw::DynamicArgumentKind::Object;
    arg.object_id = handler ? handler->object_id() : 0;
    return arg;
}"
            }
            Helper::NewIdArgument => {
                "auto new_id_argument(uint32_t object_id) -> mw::DynamicArgument
{
    mw::DynamicArgument arg{};
    arg.kind = mw::DynamicArgumentKind::NewId;
    arg.object_id = object_id;
    return arg;
}"
            }
        }
    }
}

pub fn source(protocol: &Protocol, xml_file: &str, header_name: &str) -> String {
    let mut helpers = BTreeSet::new();
    let mut body = String::new();

    register_protocol_definition(&mut body, &mut helpers, protocol);
    for interface in &protocol.interfaces {
        class_definition(&mut body, &mut helpers, protocol, interface);
    }

    let mut o = String::new();
    out!(
        o,
        "// Generated by mir_wayland_generator from {xml_file}. Do not edit."
    );
    out!(o);
    out!(o, "#include \"{header_name}\"");
    out!(o);
    out!(o, "#include <array>");
    out!(o, "#include <cmath>");
    out!(o, "#include <initializer_list>");
    out!(o, "#include <stdexcept>");
    out!(o, "#include <utility>");
    out!(o);
    out!(o, "namespace mw = mir::wayland;");
    out!(o);
    out!(o, "namespace");
    out!(o, "{{");
    for (index, helper) in helpers.iter().enumerate() {
        if index > 0 {
            out!(o);
        }
        out!(o, "{}", helper.definition());
    }
    out!(o, "}}");
    out!(o);
    out!(o, "namespace mir::wayland::{}", protocol.namespace);
    out!(o, "{{");
    o.push_str(&body);
    out!(o, "}}");
    o
}

fn register_protocol_definition(
    o: &mut String,
    helpers: &mut BTreeSet<Helper>,
    protocol: &Protocol,
) {
    out!(o, "void register_protocol()");
    out!(o, "{{");
    out!(o, "    DynamicProtocolDescriptor protocol;");
    out!(
        o,
        "    protocol.name = rust::String{{\"{}\"}};",
        protocol.name
    );
    for interface in &protocol.interfaces {
        out!(o, "    {{");
        out!(o, "        DynamicInterfaceDescriptor interface;");
        out!(
            o,
            "        interface.name = rust::String{{\"{}\"}};",
            interface.name
        );
        out!(o, "        interface.version = {};", interface.version);
        for (field, messages) in [
            ("requests", &interface.requests),
            ("events", &interface.events),
        ] {
            for message in messages {
                helpers.insert(Helper::MessageDescriptor);
                let args = join(message.args.iter().map(|arg| {
                    helpers.insert(Helper::ArgumentDescriptor);
                    format!(
                        "argument(\"{}\", DynamicArgumentKind::{}, {}, \"{}\")",
                        arg.name,
                        arg.kind.cpp_enumerator(),
                        arg.allow_null,
                        arg.interface.as_deref().unwrap_or_default()
                    )
                }));
                out!(
                    o,
                    "        interface.{field}.push_back(message(\"{}\", {}, {}, {{{args}}}));",
                    message.name,
                    message.since,
                    message.is_destructor
                );
            }
        }
        out!(
            o,
            "        protocol.interfaces.push_back(std::move(interface));"
        );
        out!(o, "    }}");
    }
    out!(o, "    register_dynamic_protocol(protocol);");
    out!(o, "}}");
}

fn class_definition(
    o: &mut String,
    helpers: &mut BTreeSet<Helper>,
    protocol: &Protocol,
    interface: &Interface,
) {
    let class = &interface.class;

    if interface.is_global {
        out!(o);
        out!(o, "auto {class}::Global::create(");
        out!(o, "    WaylandServer const& server,");
        out!(o, "    std::unique_ptr<Global> global,");
        out!(o, "    uint32_t version) -> rust::Box<DynamicGlobal>");
        out!(o, "{{");
        out!(o, "    register_protocol();");
        out!(
            o,
            "    return server.create_dynamic_global(interface_name, version, std::move(global));"
        );
        out!(o, "}}");
        out!(o);
        out!(o, "auto {class}::Global::bind(rust::Box<WaylandClient> client, rust::Box<DynamicResource> resource)");
        out!(o, "    -> std::shared_ptr<DynamicResourceHandler>");
        out!(o, "{{");
        out!(
            o,
            "    return on_bind(std::move(client), std::move(resource));"
        );
        out!(o, "}}");
    }

    out!(o);
    out!(o, "{class}::{class}(rust::Box<DynamicResource> resource)");
    out!(o, "    : resource_{{std::move(resource)}}");
    out!(o, "{{");
    out!(
        o,
        "    if (std::string{{resource_->interface_name()}} != interface_name)"
    );
    out!(o, "    {{");
    out!(o, "        throw std::invalid_argument{{");
    out!(o, "            \"Cannot handle a \" + std::string{{resource_->interface_name()}} + \" with a \" + interface_name + \" handler\"}};");
    out!(o, "    }}");
    out!(o, "}}");
    out!(o);
    out!(
        o,
        "auto {class}::resource() const -> DynamicResource const&"
    );
    out!(o, "{{");
    out!(o, "    return *resource_;");
    out!(o, "}}");
    for (name, result) in [
        ("object_id", "uint32_t"),
        ("version", "uint32_t"),
        ("is_alive", "bool"),
    ] {
        out!(o);
        out!(o, "auto {class}::{name}() const -> {result}");
        out!(o, "{{");
        out!(o, "    return resource_->{name}();");
        out!(o, "}}");
    }
    out!(o);
    out!(
        o,
        "auto {class}::client() const -> rust::Box<WaylandClient>"
    );
    out!(o, "{{");
    out!(o, "    return resource_->client();");
    out!(o, "}}");
    out!(o);
    out!(
        o,
        "void {class}::post_error(uint32_t code, std::string const& message) const"
    );
    out!(o, "{{");
    out!(o, "    resource_->post_error(code, message);");
    out!(o, "}}");
    out!(o);
    out!(o, "void {class}::destroy_resource() const");
    out!(o, "{{");
    out!(o, "    resource_->destroy();");
    out!(o, "}}");

    for (opcode, event) in interface.events.iter().enumerate() {
        if event.since > 1 {
            out!(o);
            out!(
                o,
                "auto {class}::{}() const -> bool",
                version_supports(event)
            );
            out!(o, "{{");
            out!(o, "    return version() >= {};", event.since);
            out!(o, "}}");
        }
        event_definition(o, helpers, protocol, class, opcode, event);
    }

    request_dispatch_definition(o, helpers, protocol, interface);
}

fn event_definition(
    o: &mut String,
    helpers: &mut BTreeSet<Helper>,
    protocol: &Protocol,
    class: &str,
    opcode: usize,
    event: &Message,
) {
    out!(o);
    out!(
        o,
        "void {class}::{}({}) const",
        event.method,
        event_params(protocol, event)
    );
    out!(o, "{{");
    if let Some(new_id) = event.new_id() {
        out!(o, "    if (!{})", new_id.param);
        out!(
            o,
            "        throw std::invalid_argument{{\"{}.{}: {} is null\"}};",
            class,
            event.name,
            new_id.param
        );
    }
    if event.args.is_empty() {
        out!(o, "    resource_->send_event({opcode}, {{}});");
    } else {
        let args = join(event.args.iter().map(|arg| {
            let (helper, expression) = event_argument(protocol, arg);
            helpers.insert(helper);
            expression
        }));
        out!(
            o,
            "    std::array<DynamicArgument, {}> const event_arguments{{{args}}};",
            event.args.len()
        );
        out!(o, "    resource_->send_event({opcode}, {{event_arguments.data(), event_arguments.size()}});");
    }
    if let Some(new_id) = event.new_id() {
        out!(o, "    {0}->resource().set_handler({0});", new_id.param);
    }
    out!(o, "}}");
}

fn event_argument(protocol: &Protocol, arg: &Arg) -> (Helper, String) {
    let param = &arg.param;
    match arg.kind {
        Kind::Int => (Helper::IntArgument, format!("int_argument({param})")),
        Kind::Uint => (Helper::UintArgument, format!("uint_argument({param})")),
        Kind::Fixed => (Helper::FixedArgument, format!("fixed_argument({param})")),
        Kind::String if arg.allow_null => (
            Helper::OptionalStringArgument,
            format!("optional_string_argument({param})"),
        ),
        Kind::String => (Helper::StringArgument, format!("string_argument({param})")),
        Kind::Object
            if arg
                .interface
                .as_deref()
                .and_then(|name| protocol.class_of(name))
                .is_some() =>
        {
            (
                Helper::HandlerArgument,
                format!("handler_argument({param})"),
            )
        }
        Kind::Object => (Helper::ObjectArgument, format!("object_argument({param})")),
        Kind::NewId => (
            Helper::NewIdArgument,
            format!("new_id_argument({param}->object_id())"),
        ),
        Kind::Array => (Helper::ArrayArgument, format!("array_argument({param})")),
        Kind::Fd => (Helper::FdArgument, format!("fd_argument({param})")),
    }
}

/// The expression converting `args[index]` to `arg`'s request parameter type. File
/// descriptors are taken into locals first (see [request_call]).
fn request_argument(
    helpers: &mut BTreeSet<Helper>,
    protocol: &Protocol,
    index: usize,
    arg: &Arg,
) -> String {
    let source = format!("args[{index}]");
    match arg.kind {
        Kind::Int => format!("{source}.int_value"),
        Kind::Uint => format!("{source}.uint_value"),
        Kind::Fixed => {
            helpers.insert(Helper::FromFixed);
            format!("from_fixed({source}.int_value)")
        }
        Kind::String if arg.allow_null => {
            helpers.insert(Helper::ToOptionalString);
            format!("to_optional_string({source})")
        }
        Kind::String => {
            helpers.insert(Helper::ToString);
            format!("to_string({source})")
        }
        Kind::Object => match arg
            .interface
            .as_deref()
            .and_then(|name| protocol.class_of(name))
        {
            Some(class) => {
                helpers.insert(Helper::ToHandler);
                format!("to_handler<{class}>({source})")
            }
            None => format!("{source}.object_id"),
        },
        Kind::NewId => "std::move(new_resource)".into(),
        Kind::Array => {
            helpers.insert(Helper::ToVector);
            format!("to_vector({source})")
        }
        Kind::Fd => format!("std::move(fd{index})"),
    }
}

/// Emits the case for `request`. The descriptors of received file descriptors are
/// owned by the handler, so wrap them first in case converting another argument throws.
fn request_call(
    o: &mut String,
    helpers: &mut BTreeSet<Helper>,
    protocol: &Protocol,
    opcode: usize,
    request: &Message,
) {
    let fds: Vec<usize> = request
        .args
        .iter()
        .enumerate()
        .filter(|(_, arg)| arg.kind == Kind::Fd)
        .map(|(index, _)| index)
        .collect();
    let args = join(
        request
            .args
            .iter()
            .enumerate()
            .map(|(index, arg)| request_argument(helpers, protocol, index, arg)),
    );
    let call = format!("{}({args})", request.method);
    let returns = request.new_id().is_some();

    out!(o, "    case {opcode}:");
    if !fds.is_empty() {
        out!(o, "    {{");
        for index in &fds {
            out!(o, "        mir::Fd fd{index}{{args[{index}].fd}};");
        }
    }
    if returns {
        out!(o, "        return {call};");
    } else {
        out!(o, "        {call};");
        out!(o, "        return;");
    }
    if !fds.is_empty() {
        out!(o, "    }}");
    }
}

fn request_dispatch_definition(
    o: &mut String,
    helpers: &mut BTreeSet<Helper>,
    protocol: &Protocol,
    interface: &Interface,
) {
    let class = &interface.class;
    let (constructors, others): (Vec<_>, Vec<_>) = interface
        .requests
        .iter()
        .enumerate()
        .partition(|(_, request)| request.new_id().is_some());
    let uses_args = |requests: &[(usize, &Message)]| {
        requests
            .iter()
            .any(|(_, request)| request.args.iter().any(|arg| arg.kind != Kind::NewId))
    };
    let unexpected = "    throw std::logic_error{\"Unexpected request \" + std::to_string(opcode) + \" on \" + interface_name};".to_string();

    out!(o);
    out!(
        o,
        "void {class}::on_request(uint32_t opcode, rust::Vec<DynamicArgument>{})",
        if uses_args(&others) { " args" } else { "" }
    );
    out!(o, "{{");
    if !others.is_empty() {
        out!(o, "    switch (opcode)");
        out!(o, "    {{");
        for (opcode, request) in &others {
            request_call(o, helpers, protocol, *opcode, request);
        }
        out!(o, "    }}");
    }
    out!(o, "{unexpected}");
    out!(o, "}}");

    if !constructors.is_empty() {
        out!(o);
        out!(o, "auto {class}::on_constructor_request(");
        out!(o, "    uint32_t opcode,");
        out!(
            o,
            "    rust::Vec<DynamicArgument>{},",
            if uses_args(&constructors) {
                " args"
            } else {
                ""
            }
        );
        out!(o, "    rust::Box<DynamicResource> new_resource) -> std::shared_ptr<DynamicResourceHandler>");
        out!(o, "{{");
        out!(o, "    switch (opcode)");
        out!(o, "    {{");
        for (opcode, request) in &constructors {
            request_call(o, helpers, protocol, *opcode, request);
        }
        out!(o, "    }}");
        out!(o, "{unexpected}");
        out!(o, "}}");
    }
}
